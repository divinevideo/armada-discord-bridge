import { afterAll, beforeAll, test, expect } from 'bun:test';
import postgres from 'postgres';
import { migrateModeration } from './policyStore';
import { CoopHandoff, type HandoffTransport } from './coopHandoff';
const sql = postgres(process.env.DATABASE_URL!, { onnotice: () => {} });
const caseId = crypto.randomUUID(), org = crypto.randomUUID();
beforeAll(async () => { await migrateModeration(sql); await sql`INSERT INTO moderation.cases (case_id, org_id, community_id, channel_id, rumor_id, author, fingerprint, evidence, expires_at) VALUES (${caseId}, ${org}, ${'a'.repeat(64)}, ${'b'.repeat(64)}, ${'c'.repeat(64)}, ${'d'.repeat(64)}, ${caseId}, ${Buffer.from('synthetic')}, clock_timestamp() + interval '1 hour')`; });
afterAll(async () => { await sql`DELETE FROM moderation.cases WHERE case_id = ${caseId}`; await sql.end(); });
test('durable room handoff retries after restart and transmits only an opaque case reference', async () => {
  const requests: { url: string; body: string }[] = [];
  const transport: HandoffTransport = (async (url, options) => { requests.push({ url: String(url), body: String(options?.body) }); return Response.json({}, { status: 503 }); }) ;
  const config = { origin: 'https://coop.example', apiKey: 'synthetic-api-key', orgId: org };
  await new CoopHandoff(sql, config, transport).tick();
  expect(JSON.parse(requests[0].body)).toEqual({ caseId });
  expect(requests[0].url).toBe('https://coop.example/api/v1/concord/cases');
  const [failed] = await sql`SELECT * FROM moderation.coop_handoffs WHERE case_id = ${caseId}`;
  expect(failed.state).toBe('pending'); expect(failed.attempts).toBe(1);
  await sql`UPDATE moderation.coop_handoffs SET available_at = clock_timestamp() WHERE case_id = ${caseId}`;
  const accepted: HandoffTransport = (async () => Response.json({ caseId, state: 'queued' }, { status: 202 })) ;
  await new CoopHandoff(sql, config, accepted).tick();
  const [delivered] = await sql`SELECT * FROM moderation.coop_handoffs WHERE case_id = ${caseId}`;
  expect(delivered.state).toBe('queued'); expect(delivered.attempts).toBe(2);
  expect(await new CoopHandoff(sql, config, accepted).tick()).toBe(false);
});
